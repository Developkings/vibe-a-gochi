#!/usr/bin/env python3
"""
Event sounds: one table, two outputs.

  firmware/src/sound_defs.h   note table the firmware synthesizes at runtime (no audio files in flash)
  ui/assets/sounds/*.wav      previews of exactly the same synthesis, to listen to on the PC

Style: short, soft, warm "glass marimba" — a sine with a little 2nd/3rd harmonic,
4 ms attack and an exponential decay, peaks well below full scale. Rising
intervals ask for attention, falling ones say "done".

Usage:  python ui/tools/gen_sounds.py
"""
import math, struct, wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HDR = ROOT / "firmware/src/sound_defs.h"
WAV_DIR = ROOT / "ui/assets/sounds"
RATE = 16000

N = {"F4": 349.2, "A4": 440.0, "C5": 523.3, "E5": 659.3, "G5": 784.0, "A5": 880.0, "B5": 987.8,
     "C6": 1046.5, "D6": 1174.7, "E6": 1318.5}

# name: (what triggers it, [(note, start_ms, length_ms, gain 0..1)])
SOUNDS = {
    "ATTENTION": ("Claude needs your approval", [("E5", 0, 380, 0.50), ("B5", 110, 520, 0.45)]),
    "QUESTION": ("Claude asks you a question", [("G5", 0, 300, 0.38), ("C6", 90, 300, 0.36), ("E6", 180, 480, 0.34)]),
    "DONE": ("Claude finished / stopped", [("C6", 0, 300, 0.42), ("G5", 120, 620, 0.40)]),
    "APPROVE": ("you tapped Approve", [("G5", 0, 140, 0.32), ("D6", 60, 260, 0.30)]),
    "DENY": ("you tapped Deny", [("E5", 0, 150, 0.32), ("A4", 70, 280, 0.32)]),
    "CONNECTED": ("desktop connected", [("C5", 0, 200, 0.28), ("E5", 70, 200, 0.28), ("G5", 140, 380, 0.28)]),
    "DISCONNECTED": ("desktop connection lost", [("G5", 0, 260, 0.28), ("C5", 150, 520, 0.28)]),
}

ATTACK_MS = 4
HARMONICS = [(1, 1.0), (2, 0.22), (3, 0.08)]


def voice(t, freq, length):
    """One note at time t (s) — same math as sound.cpp."""
    a = ATTACK_MS / 1000
    env = t / a if t < a else math.exp(-(t - a) / (length / 4))
    s = sum(g * math.sin(2 * math.pi * freq * k * t) for k, g in HARMONICS)
    return env * s / sum(g for _, g in HARMONICS)


def render(notes):
    end = max(st + ln for _, st, ln, _ in notes) + 20
    out = []
    for i in range(end * RATE // 1000):
        t = i / RATE
        v = 0.0
        for n, st, ln, g in notes:
            tt = t - st / 1000
            if 0 <= tt < ln / 1000:
                v += g * voice(tt, N[n], ln / 1000)
        out.append(max(-1.0, min(1.0, v)))
    return out


def main():
    WAV_DIR.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by ui/tools/gen_sounds.py — edit the table there, not here.",
             "#pragma once", "#include <stdint.h>", "",
             "struct SoundNote { float freq; uint16_t start_ms, length_ms; float gain; };",
             "struct SoundDef { const SoundNote *notes; uint8_t count; };", "",
             f"constexpr uint32_t SOUND_RATE = {RATE};",
             f"constexpr float SOUND_ATTACK_S = {ATTACK_MS / 1000}f;",
             "constexpr float SOUND_HARMONICS[][2] = {" + ", ".join(f"{{{k}, {g}f}}" for k, g in HARMONICS) + "};", "",
             "enum class Sound : uint8_t {"]
    lines += [f"  {name},  // {why}" for name, (why, _) in SOUNDS.items()]
    lines += ["  COUNT", "};", ""]
    for name, (_, notes) in SOUNDS.items():
        body = ", ".join(f"{{{N[n]}f, {st}, {ln}, {g}f}}" for n, st, ln, g in notes)
        lines.append(f"static const SoundNote SND_{name}[] = {{{body}}};")
    lines += ["", "static const SoundDef SOUNDS[] = {"]
    lines += [f"  {{SND_{name}, {len(notes)}}}," for name, (_, notes) in SOUNDS.items()]
    lines += ["};", ""]
    HDR.write_text("\n".join(lines), encoding="utf-8")

    for name, (why, notes) in SOUNDS.items():
        pcm = render(notes)
        with wave.open(str(WAV_DIR / f"{name.lower()}.wav"), "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE)
            w.writeframes(b"".join(struct.pack("<h", int(s * 32767)) for s in pcm))
        print(f"{name.lower():13s} {len(pcm) * 1000 // RATE:4d} ms  {why}")
    print(f"wrote {HDR}")


if __name__ == "__main__":
    main()
